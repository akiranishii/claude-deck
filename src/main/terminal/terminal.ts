// Opens a local terminal window that SSH-attaches to a tmux session (or a container shell).
// We write a small launcher script and hand it to Terminal.app with `open -a Terminal`, which
// needs no Automation permission. The remote command is quoted for the remote shell and then
// the whole ssh argv is quoted for the local shell (two layers, both via shq()).

import { execFile } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import type { TerminalApp } from '../../shared/types'
import { slugify } from '../../shared/naming'
import { launcherDir } from '../paths'
import { shJoin, shq } from './quote'

export interface TerminalSpec {
  title: string
  alias: string
  controlPath: string | null
  /** argv to run on the VM, e.g. ['tmux', 'attach-session', '-t', '=claude2'] */
  remoteArgs: string[]
  pathEnv: string
}

export function tmuxAttachArgs(sessionName: string, windowTarget?: string | null): string[] {
  const args = ['tmux', 'attach-session', '-t', `=${sessionName}`]
  if (windowTarget && /^[@%]\d+$/.test(windowTarget)) args.push(';', 'select-window', '-t', windowTarget)
  return args
}

export function containerShellArgs(container: string, opts: { user?: string | null; workdir?: string | null; shell?: string | null }): string[] {
  const args = ['docker', 'exec', '-it']
  if (opts.user) args.push('-u', opts.user)
  if (opts.workdir) args.push('-w', opts.workdir)
  args.push(container, opts.shell || 'bash')
  return args
}

export function buildLauncherScript(spec: TerminalSpec): string {
  const ssh = ['/usr/bin/ssh', '-t']
  if (spec.controlPath) ssh.push('-o', 'ControlMaster=no', '-o', `ControlPath=${spec.controlPath}`)
  ssh.push('-o', 'ServerAliveInterval=30', '--', spec.alias, shJoin(spec.remoteArgs))
  return [
    '#!/bin/sh',
    '# Generated by Claude Deck to open a terminal on your VM. Safe to delete.',
    `export PATH=${shq(spec.pathEnv)}`,
    `printf '\\033]0;%s\\007' ${shq(spec.title)}`,
    `exec ${shJoin(ssh)}`,
    '',
  ].join('\n')
}

function run(file: string, args: string[]): Promise<void> {
  return new Promise((resolve, reject) => {
    execFile(file, args, { timeout: 15_000 }, (err) => (err ? reject(err) : resolve()))
  })
}

export async function openTerminal(spec: TerminalSpec, app: TerminalApp): Promise<string> {
  const dir = launcherDir()
  const name = `cdeck-${slugify(spec.title, 40)}-${crypto.randomBytes(4).toString('hex')}.command`
  const file = path.join(dir, name)
  fs.writeFileSync(file, buildLauncherScript(spec), { mode: 0o700 })
  if (app === 'iterm' && fs.existsSync('/Applications/iTerm.app')) {
    if (!/^[A-Za-z0-9/._-]+$/.test(file)) throw new Error('Unexpected launcher path')
    const script = `tell application "iTerm"\n  create window with default profile command "${file}"\n  activate\nend tell`
    await run('/usr/bin/osascript', ['-e', script])
  } else {
    await run('/usr/bin/open', ['-a', 'Terminal', file])
  }
  setTimeout(() => fs.rm(file, { force: true }, () => {}), 120_000).unref()
  return file
}
